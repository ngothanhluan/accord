// A fake machine for the fixed-context tests (ST-LN-79): a repository with accord's files, a home folder with
// plugins, MCP servers, skills, agents, commands and memory, and the bench folder; test-only, so Node built-ins
// are allowed here.
import { execFileSync } from 'node:child_process';
import { appendFileSync, mkdirSync, mkdtempSync, realpathSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

export type World = { tmp: string; home: string; repo: string; bench: string; probeDir: string; memDir: string };

const slash = (p: string) => p.replace(/\\/g, '/');
const put = (file: string, text: string) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
};
const git = (cwd: string, args: string[]) =>
  execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.invalid', '-c', 'commit.gpgsign=false', ...args], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

export const MARKER = '<!-- generated by accord skills sync - do not edit - fnv1a64:0000000000000000 -->';
export const HOOK = 'npx --yes @accord-dev/accord@0.3.0 hook subagent-start';
export const POINTER = '<!-- accord:start -->\nThis repository uses accord. Type /accord.\n<!-- accord:end -->';

const agent = (name: string, model: string, tools: string | null) =>
  `---\nname: "${name}"\ndescription: "${name} does one thing."\n${tools ? `tools: "${tools}"\n` : ''}model: "${model}"\n---\n${MARKER}\n\nBody of ${name}.\n`;

/** Builds the fake machine under a new temporary folder; the caller removes `tmp`. */
export function makeWorld(): World {
  const tmp = slash(realpathSync.native(mkdtempSync(join(tmpdir(), 'bench-'))));
  const repo = `${tmp}/work/repo`;
  const home = `${tmp}/home`;
  const bench = `${tmp}/work/accord-bench`;
  const probeDir = `${tmp}/work/accord-probe`;
  mkdirSync(repo, { recursive: true });
  mkdirSync(bench, { recursive: true });
  git(repo, ['init', '-q', '-b', 'main']);

  put(`${repo}/.claude/agents/accord-scout.md`, agent('accord-scout', 'sonnet', 'Read, Grep, Glob'));
  put(`${repo}/.claude/agents/accord-critic.md`, agent('accord-critic', 'opus', 'Read, Grep, Glob'));
  put(`${repo}/.claude/agents/accord-executor.md`, agent('accord-executor', 'sonnet', null));
  put(`${repo}/.claude/agents/my-helper.md`, '---\nname: "my-helper"\ndescription: "Mine."\n---\nHelp.\n');
  put(`${repo}/.claude/skills/accord/SKILL.md`, `---\nname: "accord"\ndescription: "Use when starting work."\n---\n${MARKER}\n\nRun the check.\n`);
  put(`${repo}/.claude/skills/own-notes/SKILL.md`, '---\nname: "own-notes"\ndescription: "Notes."\n---\nWrite notes.\n');
  put(`${repo}/.claude/settings.json`, JSON.stringify({
    hooks: { SubagentStart: [{ matcher: 'accord-.*', hooks: [{ type: 'command', command: HOOK }] }] },
    enabledPlugins: { 'accord-panel@accord': true },
  }, null, 2) + '\n');
  put(`${repo}/.mcp.json`, JSON.stringify({ mcpServers: { 'proj-db': { command: 'db', args: ['--serve'] } } }, null, 2) + '\n');
  put(`${repo}/CLAUDE.md`, `${POINTER}\n\nOne own line.\n`);
  git(repo, ['add', '-A']);
  put(`${tmp}/commit.txt`, 'fixture\n');
  git(repo, ['commit', '-q', '--no-verify', '-F', `${tmp}/commit.txt`, '--cleanup=verbatim']);
  put(`${repo}/.claude/settings.local.json`, JSON.stringify({ enabledPlugins: { 'gamma@m': true } }) + '\n');
  appendFileSync(`${repo}/.git/info/exclude`, '\n.claude/settings.local.json\n');

  const enc = repo.replace(/[^A-Za-z0-9]/g, '-');
  const memDir = `${home}/.claude/projects/${enc}/memory`;
  put(`${home}/.claude/settings.json`, JSON.stringify({ enabledPlugins: { 'alpha@m': true, 'beta@m': true, 'gamma@m': false } }, null, 2) + '\n');
  put(`${home}/.claude/plugins/installed_plugins.json`, JSON.stringify({
    version: 2,
    plugins: {
      'alpha@m': [{ scope: 'user', version: '1.0.0' }],
      'beta@m': [{ scope: 'project', projectPath: 'C:\\elsewhere', version: '9.9.9' }, { scope: 'user', version: '2.0.0' }],
      'gamma@m': [{ scope: 'user', version: '3.0.0' }],
      'accord-panel@accord': [{ scope: 'project', projectPath: repo.replace(/\//g, '\\'), version: '0.3.0' }],
    },
  }, null, 2) + '\n');
  put(`${home}/.claude.json`, JSON.stringify({
    mcpServers: { 'user-search': { command: 'x', env: { API_KEY: 'sekret-user-123' } } },
    projects: { [repo]: { mcpServers: { 'local-db': { type: 'http', url: 'https://x.invalid', headers: { Authorization: 'Bearer sekret-local-456' } } } } },
  }, null, 2) + '\n');
  for (const n of ['gsd-a', 'gsd-b', 'aws-x']) put(`${home}/.claude/skills/${n}/SKILL.md`, `---\nname: "${n}"\ndescription: "${n}."\n---\nDo ${n}.\n`);
  put(`${home}/.claude/agents/gsd-r.md`, '---\nname: "gsd-r"\ndescription: "Reviews."\n---\nReview.\n');
  put(`${home}/.claude/commands/tool/run.md`, 'Run the tool.\n');
  put(`${home}/.claude/CLAUDE.md`, 'Owner line.\n');
  put(`${memDir}/MEMORY.md`, '- [Note](note.md) - a note\n');
  put(`${memDir}/note.md`, 'A note.\n');
  return { tmp, home, repo, bench, probeDir, memDir };
}
