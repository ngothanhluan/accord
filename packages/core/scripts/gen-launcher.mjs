// Emits src/generated/launcher.ts from launcher/*.mjs. Lives outside src/, so Node built-ins are allowed here.
// The launcher is plain ESM that Claude Code runs as `node .claude/accord.mjs`; it ships as text and is written by
// src/skills/plugin.ts. Not recursive: the launcher is one file.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const dir = `${root}launcher`;
const files = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isFile() && /\.mjs$/.test(d.name))
  .map((d) => d.name)
  .sort();
const body = files
  .map((f) => {
    const text = readFileSync(`${dir}/${f}`, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
    return `  ${JSON.stringify(f)}: ${JSON.stringify(text)},`;
  })
  .join('\n');
mkdirSync(`${root}src/generated`, { recursive: true });
writeFileSync(
  `${root}src/generated/launcher.ts`,
  `// Generated by scripts/gen-launcher.mjs from launcher/*.mjs. Do not edit.\nexport const launcher = {\n${body}\n} as const;\nexport type LauncherKey = keyof typeof launcher;\n`,
  'utf8',
);
console.log(`generated ${files.length} launcher files`);
