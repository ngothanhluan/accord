// Emits src/generated/panel.ts from panel/*.js. Lives outside src/, so Node built-ins are allowed here.
// The panel files are plain ESM that Claude Code loads directly; they ship as text and are written by
// src/skills/plugin.ts. Not recursive: the panel is two files.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const dir = `${root}panel`;
const files = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isFile() && /\.js$/.test(d.name))
  .map((d) => d.name)
  .sort();
const body = files
  .map((f) => {
    const text = readFileSync(`${dir}/${f}`, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
    return `  ${JSON.stringify(f)}: ${JSON.stringify(text)},`;
  })
  .join('\n');
mkdirSync(`${root}src/generated`, { recursive: true });
writeFileSync(
  `${root}src/generated/panel.ts`,
  `// Generated by scripts/gen-panel.mjs from panel/*.js. Do not edit.\nexport const panel = {\n${body}\n} as const;\nexport type PanelKey = keyof typeof panel;\n`,
  'utf8',
);
console.log(`generated ${files.length} panel files`);
