// Phase 11 G1 (D-01): `accord skills sync` renders the `agents:` block of accord/config.yml into the agent files, and a
// second sync reports them unchanged and writes nothing.
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { parse } from 'yaml';
import { CONFIG } from '../../../test/helpers/lane.js';
import { cleanup, makeRepo, run, writeFiles } from './helpers/repo.js';

const repos: string[] = [];
afterEach(() => {
  while (repos.length > 0) cleanup(repos.pop() as string);
});

const EXECUTOR = '.claude/agents/accord-executor.md';
const REVIEWER = '.claude/agents/accord-reviewer.md';
const at = (repo: string, path: string): string => join(repo, ...path.split('/'));
const frontmatter = (text: string): Record<string, unknown> => parse(text.split('---\n')[1] as string) as Record<string, unknown>;

it('risk:regression agents.executor.mcp and agents.reviewer.skills reach their agent files, and a second sync changes nothing (11-ac-1, D-01)', async () => {
  const repo = makeRepo();
  repos.push(repo);
  writeFiles(repo, { 'accord/config.yml': CONFIG + 'agents:\n  executor:\n    mcp: [playwright]\n  reviewer:\n    skills: [x]\n' });

  const first = await run(['skills', 'sync'], repo);
  expect(first.code, first.err).toBe(0);
  expect(first.out).toContain('created ' + EXECUTOR);
  const executor = readFileSync(at(repo, EXECUTOR), 'utf8');
  const fm = frontmatter(executor);
  expect(fm.mcpServers).toEqual(['playwright']);
  expect(String(fm.tools).endsWith('mcp__playwright__*')).toBe(true);
  const head = executor.split('---\n')[1] as string;
  expect(head.indexOf('effort:')).toBeLessThan(head.indexOf('mcpServers:'));
  expect(executor.indexOf('mcpServers:')).toBeLessThan(executor.indexOf('<!-- generated by accord'));
  expect(frontmatter(readFileSync(at(repo, REVIEWER), 'utf8')).skills).toEqual(['x']);

  const before = [EXECUTOR, REVIEWER].map((p) => statSync(at(repo, p)).mtimeMs);
  const second = await run(['skills', 'sync'], repo);
  expect(second.code, second.err).toBe(0);
  expect(second.out).toContain('unchanged ' + EXECUTOR);
  expect(second.out).toContain('unchanged ' + REVIEWER);
  expect([EXECUTOR, REVIEWER].map((p) => statSync(at(repo, p)).mtimeMs)).toEqual(before);
});
