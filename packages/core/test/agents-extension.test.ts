// Phase 11 G1 (D-01): `agents:` in accord/config.yml adds MCP servers, skills and tools to an agent by role, and the
// renderer merges them into the agent's frontmatter after the authored fields. The judge and the foreign reviewer take none.
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import { AGENT_DEFAULTS, AGENT_LOCKS, agentsProblems, agentsRefusal, agents, agentTargets, loadConfig, NO_ADDITIONS, renderAgent } from '../src/index.js';
import type { AccordConfig, AgentKey, AgentProblem, McpEntry, RouteKey } from '../src/index.js';

const config = (over: Partial<AccordConfig> = {}): AccordConfig =>
  ({ accord: '0.1.0', profile: 'build', tracker: { adapter: 'none' }, design: { tokens: '' }, roles: ['ba', 'dev'], runtimes: ['claude'], ...over }) as AccordConfig;
const fileOf = (c: AccordConfig, name: string): string => agentTargets(c).find((f) => f.path === `.claude/agents/${name}.md`)?.text ?? '';
const frontmatter = (text: string): Record<string, unknown> => parse(text.split('---\n')[1] as string) as Record<string, unknown>;

describe('agents: additions render into the agent files (D-01)', () => {
  it('risk:regression agents.reviewer.skills renders under skills of accord-reviewer.md and nowhere else (11-ac-1, D-01)', () => {
    const c = config({ agents: { reviewer: { skills: ['x'] } } });
    const reviewer = fileOf(c, 'accord-reviewer');
    expect(frontmatter(reviewer).skills).toEqual(['x']);
    // the fields keep their order: the authored ones, then model and effort, then skills, all before the marker
    const head = reviewer.split('---\n')[1] as string;
    expect(head.indexOf('effort:')).toBeLessThan(head.indexOf('skills:'));
    expect(reviewer.indexOf('skills:')).toBeLessThan(reviewer.indexOf('<!-- generated by accord'));
    expect(frontmatter(fileOf(c, 'accord-executor')).skills).toBeUndefined();
  });

  it('risk:regression agents.executor.mcp renders mcpServers and adds mcp__playwright__* to the executor allowlist (11-ac-1, 11-ac-3, D-01)', () => {
    const executor = fileOf(config({ agents: { executor: { mcp: ['playwright'] } } }), 'accord-executor');
    const fm = frontmatter(executor);
    expect(fm.mcpServers).toEqual(['playwright']);
    expect(String(fm.tools).endsWith(', mcp__playwright__*')).toBe(true);
    const head = executor.split('---\n')[1] as string;
    expect(head.indexOf('effort:')).toBeLessThan(head.indexOf('mcpServers:'));
  });

  it('risk:regression with no agents key every rendered file is what it is today (11-ac-1, D-01)', () => {
    const plain = agentTargets(config());
    expect(agentTargets(config({ agents: {} }))).toEqual(plain);
    for (const key of Object.keys(agents) as AgentKey[]) {
      const authored = parse((agents[key].split('---\n')[1]) as string) as { name: string; route: keyof typeof AGENT_DEFAULTS };
      const found = plain.find((f) => f.path === `.claude/agents/${authored.name}.md`)?.text;
      expect(found).toBe(renderAgent(key, AGENT_DEFAULTS[authored.route]));
    }
  });
});

const mcpOf = (c: AccordConfig, name: string): unknown => frontmatter(fileOf(c, name)).mcpServers;
const toolsOf = (c: AccordConfig, name: string): string => String(frontmatter(fileOf(c, name)).tools);

describe('agents: each role gets exactly its own additions (11-ac-3, Security Ruling)', () => {
  it('risk:regression a server added to a role with an allowlist adds mcp__<server>__* once (11-ac-3, D-01)', () => {
    expect(toolsOf(config({ agents: { reviewer: { mcp: ['docs'] } } }), 'accord-reviewer')).toBe('Read, Grep, Glob, Bash, mcp__docs__*');
    expect(toolsOf(config({ agents: { reviewer: { mcp: ['reports__v2'] } } }), 'accord-reviewer')).toBe('Read, Grep, Glob, Bash, mcp__reports__v2__*');
    // a server an added tools entry already covers is not listed twice, and the covering entry stays where the team wrote it
    expect(toolsOf(config({ agents: { reviewer: { mcp: ['docs'], tools: ['mcp__docs__*'] } } }), 'accord-reviewer')).toBe('Read, Grep, Glob, Bash, mcp__docs__*');
    expect(toolsOf(config({ agents: { reviewer: { mcp: ['docs'], tools: ['mcp__docs'] } } }), 'accord-reviewer')).toBe('Read, Grep, Glob, Bash, mcp__docs');
  });

  it('risk:regression an agent that authors no tools line gains none (11-ac-3, D-01, T-11-05)', () => {
    const fm = frontmatter(fileOf(config({ agents: { researcher: { mcp: ['docs'], tools: ['WebFetch'] } } }), 'accord-researcher'));
    expect(fm.mcpServers).toEqual(['docs']);
    expect(Object.hasOwn(fm, 'tools')).toBe(false);
    const plain = frontmatter(fileOf(config(), 'accord-researcher'));
    expect(fm.disallowedTools).toBe(plain.disallowedTools);
    expect(String(fm.disallowedTools)).toContain('Edit');
  });

  it('risk:regression agents.executor.tools appends each tool once after the authored ones, in the order written (D-01)', () => {
    expect(toolsOf(config({ agents: { executor: { tools: ['WebFetch', 'Read', 'WebSearch'] } } }), 'accord-executor')).toBe('Read, Write, Edit, Bash, Grep, Glob, WebFetch, WebSearch');
  });

  it('risk:security the judge and the foreign reviewer render the same with and without additions (Security Ruling, T-11-02)', () => {
    expect([...NO_ADDITIONS].sort()).toEqual(['foreign-reviewer.md', 'judge.md']);
    const all = { mcp: ['docs', { playwright: { type: 'http', url: 'https://example.test/mcp' } }], skills: ['x'], tools: ['WebFetch', 'Write'] };
    const loaded = config({ agents: { reviewer: all, 'reviewer.final': all } } as Partial<AccordConfig>);
    for (const name of ['accord-judge', 'accord-foreign-reviewer']) {
      const without = fileOf(config(), name);
      expect(without.length).toBeGreaterThan(0);
      expect(fileOf(loaded, name)).toBe(without);
    }
    // and the same additions do reach the two agents they address
    expect(mcpOf(loaded, 'accord-reviewer')).toBeDefined();
    expect(mcpOf(loaded, 'accord-final-reviewer')).toBeDefined();
  });

  it('risk:regression agents.reviewer reaches accord-reviewer.md only and agents.reviewer.final accord-final-reviewer.md only (Security Ruling, D-01)', () => {
    const base = config({ agents: { reviewer: { skills: ['x'] } } });
    expect(frontmatter(fileOf(base, 'accord-reviewer')).skills).toEqual(['x']);
    expect(frontmatter(fileOf(base, 'accord-final-reviewer')).skills).toBeUndefined();
    const final = config({ agents: { 'reviewer.final': { skills: ['y'] } } });
    expect(frontmatter(fileOf(final, 'accord-final-reviewer')).skills).toEqual(['y']);
    expect(frontmatter(fileOf(final, 'accord-reviewer')).skills).toBeUndefined();
  });

  it('risk:regression an inline http, sse or ws definition renders as the one-key object and adds mcp__<name>__* (D-17 render half, 11-ac-3)', () => {
    const inline = { playwright: { type: 'http', url: 'https://example.test/mcp' } } as const;
    const fm = frontmatter(fileOf(config({ agents: { executor: { mcp: [inline] } } }), 'accord-executor'));
    expect(fm.mcpServers).toEqual([inline]);
    expect(String(fm.tools).endsWith('mcp__playwright__*')).toBe(true);
    for (const type of ['sse', 'ws'] as const) {
      const other = { remote: { type, url: type === 'ws' ? 'wss://example.test/x' : 'https://example.test/x' } };
      expect(mcpOf(config({ agents: { verifier: { mcp: [other] } } }), 'accord-verifier')).toEqual([other]);
    }
  });
});

describe('agents: the schema refuses what the lock cannot take (Security Ruling, D-17)', () => {
  const base = 'accord: "0.22.0"\nprofile: build\ntracker:\n  adapter: none\ndesign:\n  tokens: ""\nroles: [ba, dev]\nruntimes: [claude]\n';
  const check = (text: string): { ok: boolean; found: string[] } => {
    const { config: loaded, findings } = loadConfig('accord/config.yml', base + 'agents:\n' + text);
    return { ok: loaded !== undefined, found: findings.map((f) => f.pointer ?? f.reason) };
  };
  const loads = (text: string): void => expect(check(text), text).toMatchObject({ ok: true });
  const refuses = (text: string): void => {
    const got = check(text);
    expect(got.ok, text).toBe(false);
    expect(got.found.some((p) => p.startsWith('/agents')), text + ' -> ' + JSON.stringify(got.found)).toBe(true);
  };

  it('risk:security a well-formed agents block loads, every route key included (11-ac-1, D-01)', () => {
    loads('  scout: { skills: [a] }\n  critic: { skills: [a] }\n  planner: { skills: [a] }\n  executor: { mcp: [playwright], tools: [WebFetch, "mcp__docs__*"] }\n');
    loads('  reviewer: { mcp: [docs] }\n  reviewer.final: { mcp: [docs] }\n  verifier: { skills: [a] }\n  debugger: { skills: [a] }\n  researcher: { mcp: [docs] }\n');
    loads('  executor:\n    mcp:\n      - playwright:\n          type: http\n          url: https://example.test/mcp\n');
  });

  it('risk:security a role that is not a route key is a schema error, the judge and foreign reviewer included (Security Ruling, T-11-02)', () => {
    for (const role of ['judge', 'foreign-reviewer', 'auditor', 'architect', 'nosuch']) refuses('  ' + role + ': { skills: [a] }\n');
  });

  it('risk:security 33 skills, a bad server name and a bad skill or tool name are schema errors (T-11-06, D-01)', () => {
    const names = Array.from({ length: 33 }, (_, i) => 's' + i);
    refuses('  reviewer: { skills: [' + names.join(', ') + '] }\n');
    loads('  reviewer: { skills: [' + names.slice(0, 32).join(', ') + '] }\n');
    refuses('  executor: { mcp: ["-leading"] }\n');
    refuses('  executor: { mcp: ["has space"] }\n');
    refuses('  reviewer: { skills: ["Has Upper"] }\n');
    refuses('  reviewer: { skills: [a, a] }\n');
    refuses('  reviewer: { tools: ["two words"] }\n');
  });

  it('risk:security an inline definition carries no env, headers or credential in its url (T-11-04, D-17)', () => {
    const inline = (lines: string): string => '  executor:\n    mcp:\n      - s:\n          type: http\n' + lines;
    loads(inline('          url: https://example.test/mcp\n'));
    refuses(inline('          url: https://example.test/mcp\n          env: { TOKEN: abc }\n'));
    refuses(inline('          url: https://example.test/mcp\n          headers: { Authorization: abc }\n'));
    refuses(inline('          url: https://user:pass@example.test/mcp\n'));
    refuses('  executor:\n    mcp:\n      - s:\n          type: ftp\n          url: https://example.test/mcp\n');
    refuses('  executor:\n    mcp:\n      - a: { type: http }\n        b: { type: http }\n');
  });

  // RESEARCH A2, settled in .planning/phases/11-agent-extension-by-role/11-A2-PROBE.md (a private planning record, not in this repository): the docs are silent on which
  // name form the `skills:` field resolves for a plugin skill, so the probe's "Settled form" is `open` and its "Use" is `both`. accord therefore never rewrites a name.
  it('risk:parsing a skill name renders verbatim in bare and plugin form (RESEARCH A2, D-01)', () => {
    const names = ['impeccable', 'impeccable:impeccable', 'ui-ux-pro-max:ui-ux-pro-max'];
    loads('  reviewer: { skills: [impeccable, "impeccable:impeccable", "ui-ux-pro-max:ui-ux-pro-max"] }\n');
    const reviewer = fileOf(config({ agents: { reviewer: { skills: names } } }), 'accord-reviewer');
    expect(frontmatter(reviewer).skills).toEqual(names);
    // each name sits on its own line of the rendered list, in the order written
    const lines = (reviewer.split('---\n')[1] as string).split('\n');
    const at = lines.indexOf('skills:');
    expect(lines.slice(at + 1, at + 4).map((l) => l.trim().replace(/^- /, '').replace(/^"(.*)"$/, '$1'))).toEqual(names);
  });
});

describe('agents: a tool the rule of a role forbids is refused by name (11-ac-2, D-02)', () => {
  it('risk:security agents.reviewer.tools [Write] is one problem naming the role, the entry and the reviewer rule, and agentsRefusal prints it (11-ac-2, D-02)', () => {
    const c = config({ agents: { reviewer: { tools: ['Write'] } } });
    const problems = agentsProblems(c);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ role: 'reviewer', field: 'tools', entry: 'Write', index: 0 });
    expect(problems[0]?.reason).toContain('never edits');
    const lines = agentsRefusal(problems).split('\n');
    expect(lines[0]).toBe('agents.reviewer.tools: Write: ' + problems[0]?.reason);
    expect(lines.at(-1)).toBe('nothing was written');
  });

  it('risk:security agentTargets never throws on a refused entry and leaves it out of the rendered tools (11-ac-2, D-02)', () => {
    const c = config({ agents: { reviewer: { tools: ['Write', 'WebFetch'] } } });
    const reviewer = fileOf(c, 'accord-reviewer');
    expect(reviewer.length).toBeGreaterThan(0);
    expect(agentTargets(c)).toHaveLength(agentTargets(config()).length);
    expect(toolsOf(c, 'accord-reviewer')).toBe('Read, Grep, Glob, Bash, WebFetch');
    expect(agentsProblems(config())).toEqual([]);
  });

  const refusedBy = (role: RouteKey, tools: string[]): string[] =>
    agentsProblems(config({ agents: { [role]: { tools } } } as Partial<AccordConfig>)).map((p) => p.entry);
  const every = ['Edit', 'Write', 'MultiEdit', 'NotebookEdit', 'Bash', 'PowerShell', 'Agent', 'Task'];

  it('risk:security each role refuses the tools its authored rule forbids and takes the rest (11-ac-2, D-02)', () => {
    const forbidden: Record<string, string[]> = {
      scout: every,
      critic: every,
      reviewer: ['Edit', 'Write', 'MultiEdit', 'NotebookEdit', 'Agent', 'Task'],
      'reviewer.final': ['Edit', 'Write', 'MultiEdit', 'NotebookEdit', 'Agent', 'Task'],
      planner: ['Bash', 'PowerShell', 'NotebookEdit', 'Agent', 'Task'],
      verifier: ['NotebookEdit', 'Agent', 'Task'],
      debugger: ['NotebookEdit', 'Agent', 'Task'],
      executor: ['Agent', 'Task'],
    };
    for (const [role, tools] of Object.entries(forbidden)) {
      for (const tool of every) {
        expect(refusedBy(role as RouteKey, [tool]), role + ' ' + tool).toEqual(tools.includes(tool) ? [tool] : []);
      }
      expect(refusedBy(role as RouteKey, ['WebFetch', 'WebSearch', 'Read']), role).toEqual([]);
    }
  });

  it('risk:security every read-only role locks every command-running and outward tool the researcher row locks, and a reviewer the outward ones (11-ac-2, D-02)', () => {
    const outward = ['Artifact', 'ShareOnboardingGuide', 'RemoteTrigger', 'CronCreate', 'SendMessage'];
    const reaching = AGENT_LOCKS.researcher.filter((t) => !['Edit', 'Write', 'NotebookEdit', 'Bash', 'PowerShell', 'Agent', 'Task'].includes(t));
    expect(reaching).toEqual(expect.arrayContaining(['Monitor', ...outward]));
    for (const role of ['scout', 'critic', 'planner'] as RouteKey[]) {
      for (const tool of reaching) expect(refusedBy(role, [tool]), role + ' ' + tool).toEqual([tool]);
    }
    for (const role of ['reviewer', 'reviewer.final'] as RouteKey[]) {
      for (const tool of outward) expect(refusedBy(role, [tool]), role + ' ' + tool).toEqual([tool]);
    }
    // a reviewer runs tests and runs git, so the tools that run a command stay open to it, and the executor, verifier and debugger keep their rows
    expect(refusedBy('reviewer', ['Bash', 'Monitor'])).toEqual([]);
    for (const role of ['executor', 'verifier', 'debugger'] as RouteKey[]) expect(refusedBy(role, ['Monitor', 'SendMessage']), role).toEqual([]);
    // the failing case of the review: agents.scout.tools [Monitor] is refused by name and the scout file gains no tools entry
    expect(toolsOf(config({ agents: { scout: { tools: ['Monitor'] } } }), 'accord-scout')).toBe('Read, Grep, Glob');
  });

  it('risk:security a specifier is compared on the name before its parenthesis, and a name on its case (11-ac-2, D-02)', () => {
    expect(refusedBy('scout', ['Bash(git push *)'])).toEqual(['Bash(git push *)']);
    expect(refusedBy('reviewer', ['Write(src/**)', 'Bash(git log *)'])).toEqual(['Write(src/**)']);
    expect(refusedBy('critic', ['write'])).toEqual(['write']);
    // a comma inside one entry would split in the rendered list, so each piece is judged: a locked tool cannot ride behind a permitted one
    expect(refusedBy('reviewer', ['Bash(x), Write(y)'])).toEqual(['Bash(x), Write(y)']);
  });

  it('risk:security an mcp__<server>__* tools entry is never refused, on any role (D-03)', () => {
    for (const role of Object.keys(AGENT_DEFAULTS) as RouteKey[]) {
      expect(refusedBy(role, ['mcp__docs__*', 'mcp__docs', 'mcp__docs__Write']), role).toEqual([]);
    }
    // and a server on a read-only role renders: reachable, not refused
    expect(toolsOf(config({ agents: { scout: { mcp: ['docs'] } } }), 'accord-scout')).toBe('Read, Grep, Glob, mcp__docs__*');
  });

  it('risk:security AGENT_LOCKS holds, for the researcher, every name of its authored disallowedTools, and no role locks a tool its own source allows (11-ac-2, D-02)', () => {
    const authored = (key: AgentKey): Record<string, unknown> => parse(agents[key].split('---\n')[1] as string) as Record<string, unknown>;
    const names = (value: unknown): string[] => String(value ?? '').split(',').map((t) => t.trim()).filter((t) => t !== '');
    expect([...AGENT_LOCKS.researcher].sort()).toEqual(names(authored('researcher.md').disallowedTools).sort());
    for (const key of Object.keys(agents) as AgentKey[]) {
      const source = authored(key);
      const role = source.route as RouteKey;
      if (NO_ADDITIONS.includes(key) || key === 'researcher.md') continue;
      for (const name of names(source.tools)) expect(AGENT_LOCKS[role], key + ' ' + name).not.toContain(name);
    }
    expect(Object.keys(AGENT_LOCKS).sort()).toEqual(Object.keys(AGENT_DEFAULTS).sort());
  });

  it('risk:security every agents.researcher.tools entry is refused, since it authors no allowlist and an entry adds nothing, and its file gains no tools line (11-ac-2, D-02, T-11-05)', () => {
    const problems = agentsProblems(config({ agents: { researcher: { tools: ['WebFetch', 'Read', 'Write'] } } }));
    expect(problems.map((p) => p.entry)).toEqual(['WebFetch', 'Read', 'Write']);
    for (const p of problems) expect(p.reason).toContain('authors no tools allowlist');
    // D-03 still holds there: a server entry is not refused (it adds nothing to the researcher either, and the server itself renders through mcp)
    expect(agentsProblems(config({ agents: { researcher: { tools: ['mcp__docs__*'] } } }))).toEqual([]);
    expect(Object.hasOwn(frontmatter(fileOf(config({ agents: { researcher: { tools: ['WebFetch'] } } }), 'accord-researcher')), 'tools')).toBe(false);
  });
});

describe('agents: an inline server that would run a command is refused (D-17, T-11-03)', () => {
  const local: McpEntry = { local: { type: 'stdio', command: 'node', args: ['x.js'] } };
  const problemsOf = (mcp: McpEntry[]): AgentProblem[] => agentsProblems(config({ agents: { executor: { mcp } } }));

  it('risk:security an inline stdio server is one problem naming the role, the server, the reason and the fix (D-17)', () => {
    const [problem, ...rest] = problemsOf([local]);
    expect(rest).toEqual([]);
    expect(problem).toMatchObject({ role: 'executor', field: 'mcp', index: 0, entry: 'local' });
    expect(problem?.reason).toContain("run a command from a committed file on every teammate's machine");
    expect(problem?.reason).toContain('install the server in Claude Code and name it');
    expect(agentsRefusal(problemsOf([local])).split('\n')[0]).toBe('agents.executor.mcp: local: ' + problem?.reason);
  });

  it('risk:security a plain server name and an inline http, sse or ws with a url pass; one with no url is refused (D-17)', () => {
    expect(problemsOf(['playwright', { docs: { type: 'http', url: 'https://example.test/mcp' } }, { w: { type: 'ws', url: 'wss://example.test/x' } }])).toEqual([]);
    for (const type of ['http', 'sse', 'ws'] as const) {
      const [problem] = problemsOf([{ docs: { type } }]);
      expect(problem, type).toMatchObject({ role: 'executor', field: 'mcp', index: 0, entry: 'docs' });
      expect(problem?.reason).toContain('no url');
    }
  });

  it('risk:security a command or args on an http, sse or ws server is refused as well (D-17)', () => {
    expect(problemsOf([{ docs: { type: 'http', url: 'https://example.test/mcp', command: 'node' } }])).toHaveLength(1);
    expect(problemsOf([{ docs: { type: 'sse', url: 'https://example.test/mcp', args: ['x'] } }])).toHaveLength(1);
  });

  it('risk:security an inline server whose url carries a query string, a fragment or userinfo is refused, naming the role, the server and the fix (11-01 credential-in-url prohibition, D-17)', () => {
    const urls = ['https://example.test/mcp?token=abc', 'https://example.test?key=1', 'https://example.test/mcp#frag', 'https://user:pw@example.test/mcp', 'wss://example.test/x?a=b'];
    for (const url of urls) {
      const type = url.startsWith('ws') ? 'ws' : 'http';
      const [problem, ...rest] = problemsOf([{ docs: { type, url } }]);
      expect(rest, url).toEqual([]);
      expect(problem, url).toMatchObject({ role: 'executor', field: 'mcp', index: 0, entry: 'docs' });
      expect(problem?.reason, url).toContain('credential or token in a url is refused');
      expect(problem?.reason, url).toContain('install the server in Claude Code and name it in agents.executor.mcp');
    }
    // a path with no query, fragment or userinfo still passes; so does an `@` after the authority
    expect(problemsOf([{ docs: { type: 'http', url: 'https://example.test/mcp/v1' } }])).toEqual([]);
    // the refused server is left out of the render, as any refused entry is
    expect(Object.hasOwn(frontmatter(fileOf(config({ agents: { executor: { mcp: [{ docs: { type: 'http', url: urls[0] as string } }] } } }), 'accord-executor')), 'mcpServers')).toBe(false);
  });

  it('risk:security agentTargets leaves a refused server out and never throws, so the rest of the config still renders (D-17)', () => {
    const c = config({ agents: { executor: { mcp: [local, 'playwright', { docs: { type: 'http' } }] } } });
    const fm = frontmatter(fileOf(c, 'accord-executor'));
    expect(fm.mcpServers).toEqual(['playwright']);
    expect(String(fm.tools).endsWith(', mcp__playwright__*')).toBe(true);
    expect(String(fm.tools)).not.toContain('local');
    // every server refused: no mcpServers key at all
    expect(Object.hasOwn(frontmatter(fileOf(config({ agents: { executor: { mcp: [local] } } }), 'accord-executor')), 'mcpServers')).toBe(false);
  });
});
