/** The rendered frontmatter block parsed with yaml, or null when there is none. A `[a-z-]+:` scan would also
 *  match prose in a body — the block is machine-written and small, so parsing it is both safer and shorter. */
function frontmatter(md: string): Record<string, unknown> | null {
  const m = FRONTMATTER.exec(md);
  return m ? (parse(m[1], { schema: 'core', customTags: stringNumerics }) as Record<string, unknown>) : null;
}

