// Phase 7 (07-01): the accord skill stopped loading seven reference files, so old intact copies went. Phase 8.3 (08.3-05): the accord folder renders five of them
// again (the lane, finish and scout files its Continue steps and lane routes read), so only `security` and `upgrade` stay retired.
it('risk:stale-file sync removes the retired accord reference copies and never renders them again', async () => {
  const repo = sandbox('[claude, codex]');
  const retired = ['security', 'upgrade'];
  const rendered = ['finish', 'lane', 'lane-r', 'lane-s', 'scout'];
  const pathsOf = (names: string[]) => ['.claude/skills', '.agents/skills'].flatMap((dir) => names.map((n) => dir + '/accord/' + n + '.md'));
  const paths = pathsOf(retired);
  const written = pathsOf(rendered);
  const body = '\n# An old reference copy\n';
  const old = '<!-- generated by accord skills sync - do not edit - ' + contentHash(body) + ' -->\n' + body;
  for (const p of [...paths, ...written]) {
    mkdirSync(at(repo, p.slice(0, p.lastIndexOf('/'))), { recursive: true });
    writeFileSync(at(repo, p), old);
  }

  const first = await run(['skills', 'sync'], repo);
  expect(first.code, first.err).toBe(0);
  const out = first.out.split('\n');
  for (const p of paths) {
    expect(out, p).toContain('removed ' + p);
    expect(existsSync(at(repo, p)), p).toBe(false);
  }
  // the five the accord folder renders again are rewritten, never removed
  for (const p of written) {
    expect(out, p).toContain('updated ' + p);
    expect(out, p).not.toContain('removed ' + p);
    expect(readFileSync(at(repo, p), 'utf8'), p).not.toBe(old);
  }
  expect(existsSync(at(repo, '.claude/skills/accord-new'))).toBe(false);
  expect(existsSync(at(repo, '.claude/skills/accord/SKILL.md'))).toBe(true);

  const second = await run(['skills', 'sync'], repo);
  expect(second.out).not.toContain('removed');
  for (const p of paths) expect(existsSync(at(repo, p)), p).toBe(false);
  for (const p of written) expect(existsSync(at(repo, p)), p).toBe(true);
}, 120_000);

// Phase 8.3 D-01: a command that became a file of /accord leaves a team's repository whole: every file accord rendered, while unedited, then the emptied folder.
// The cases read the lists from core, so each later fold and each retired reference of the accord folder is covered with no edit here.
const SKILL_DIRS = ['.claude/skills', '.agents/skills'];
const isSkillPath = (p: string): boolean => SKILL_DIRS.some((d) => p.startsWith(d + '/'));
/** An intact old copy of a skill file: the marker hash is the hash of the text around it. */
const oldCopy = (body = '\n# An old copy\n'): string => '<!-- generated by accord skills sync - do not edit - ' + contentHash(body) + ' -->\n' + body;
const foldersOf = (): [string, readonly string[]][] => Object.entries(RETIRED_SKILL_FOLDERS);

function putAll(repo: string, paths: readonly string[], text: string = oldCopy()): void {
  for (const p of paths) {
    mkdirSync(at(repo, p.slice(0, p.lastIndexOf('/'))), { recursive: true });
    writeFileSync(at(repo, p), text);
  }
}

it('risk:data-loss sync removes every retired command folder whole and a second run removes nothing (D-01)', async () => {
  const repo = sandbox('[claude, codex]');
  const paths = RETIRED_FILES.filter(isSkillPath);
  const folders = foldersOf().flatMap(([folder]) => SKILL_DIRS.map((dir) => dir + '/' + folder));
  expect(folders.length, 'no retired folder is listed').toBeGreaterThan(0);
  putAll(repo, paths);

  const first = await run(['skills', 'sync'], repo);
  expect(first.code, first.err).toBe(0);
  const out = first.out.split('\n');
  for (const p of paths) {
    expect(out, p).toContain('removed ' + p);
    expect(existsSync(at(repo, p)), p).toBe(false);
  }
  for (const f of folders) {
    expect(out, f).toContain('removed ' + f);
    expect(existsSync(at(repo, f)), f).toBe(false);
    expect(first.err, f).not.toContain(f);
  }
  expect(existsSync(at(repo, '.claude/skills/accord/SKILL.md'))).toBe(true);
  expect(existsSync(at(repo, '.agents/skills/accord/SKILL.md'))).toBe(true);

  const second = await run(['skills', 'sync'], repo);
  expect(second.code, second.err).toBe(0);
  expect(second.out).not.toContain('removed');
  for (const f of folders) expect(second.err, f).not.toContain(f);
}, 120_000);

it('risk:data-loss sync keeps an edited file of an old command folder and lists the folder as an orphan (D-01)', async () => {
  const repo = sandbox('[claude, codex]');
  const [folder, held] = foldersOf().find(([name]) => name === 'accord-queue') ?? ['', []];
  expect(held.length, 'accord-queue has no retire entry').toBeGreaterThan(1);
  const dir = '.claude/skills/' + folder;
  const siblings = held.filter((f) => f !== 'SKILL.md').map((f) => dir + '/' + f);
  putAll(repo, siblings);
  const edited = oldCopy() + 'a hand edit\n';
  putAll(repo, [dir + '/SKILL.md'], edited);

  const r = await run(['skills', 'sync'], repo);
  expect(r.code, r.err).toBe(0);
  expect(readFileSync(at(repo, dir + '/SKILL.md'), 'utf8')).toBe(edited);
  expect(existsSync(at(repo, dir))).toBe(true);
  for (const s of siblings) {
    expect(existsSync(at(repo, s)), s).toBe(false);
    expect(r.out.split('\n'), s).toContain('removed ' + s);
  }
  expect(r.out.split('\n')).not.toContain('removed ' + dir);
  expect(r.err).toContain('orphan ' + dir);
}, 120_000);

