// Phase 11 G3 (D-07, 11-ac-8): `ui.build` reaches the executor of a `ui: true` ticket through a second rendered executor, `accord-executor-ui`, that `accord brief` names;
// `ui.review` gets the same technique for the `ui` lens reviewer. A static agent file cannot depend on the ticket, so the plain accord-executor never carries the skill.
// Skill-name form (11-A2-PROBE.md, `Use: both`): each case that names a real skill runs with the bare name and with the plugin name, and accord renders either verbatim (A2).
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import { agentTargets, EXECUTOR_AGENTS, UI_EXECUTOR, UI_REVIEWER } from '../src/index.js';
import type { AccordConfig } from '../src/index.js';

const config = (over: Partial<AccordConfig> = {}): AccordConfig =>
  ({ accord: '0.1.0', profile: 'build', tracker: { adapter: 'none' }, design: { tokens: '' }, roles: ['ba', 'dev'], runtimes: ['claude'], ...over }) as AccordConfig;
const fileOf = (c: AccordConfig, name: string): string | undefined => agentTargets(c).find((f) => f.path === `.claude/agents/${name}.md`)?.text;
const frontmatter = (text: string | undefined): Record<string, unknown> => parse((text ?? '').split('---\n')[1] as string) as Record<string, unknown>;
/** The text after the marker line: the authored body, the same in every render of one definition. */
const bodyOf = (text: string | undefined): string => (text ?? '').split(/^<!-- generated by accord skills sync .* -->\n/m).pop() as string;
const FORMS =['impeccable', 'impeccable:impeccable'] as const;

describe('ui.build renders accord-executor-ui from the executor definition (11-ac-8, D-07)', () => {
  it('risk:regression the names are accord-executor-ui, accord-reviewer-ui and the executor set (11-ac-8, D-07)', () => {
    expect(UI_EXECUTOR).toBe('accord-executor-ui');
    expect(UI_REVIEWER).toBe('accord-reviewer-ui');
    expect([...EXECUTOR_AGENTS]).toEqual(['accord-executor', 'accord-executor-ui']);
  });

  for (const form of FORMS) {
    it(`risk:regression ui.build ${form} renders accord-executor-ui with that skill first and the executor's tools, model and effort (11-ac-8, D-07)`, () => {
      const c = config({ ui: { build: form } });
      const ui = fileOf(c, UI_EXECUTOR);
      expect(ui, 'the variant is rendered').toBeDefined();
      const fm = frontmatter(ui);
      const plain = frontmatter(fileOf(c, 'accord-executor'));
      expect(fm.name).toBe('accord-executor-ui');
      expect(fm.skills).toEqual([form]);
      expect(fm.tools).toBe(plain.tools);
      expect(fm.model).toBe(plain.model);
      expect(fm.effort).toBe(plain.effort);
      expect(fm.description).toBe(plain.description);
      // the skill name is rendered verbatim, never rewritten into the other form (A2)
      expect(ui).toContain(form);
      // the body is the executor's, whole
      expect(bodyOf(ui)).toBe(bodyOf(fileOf(c, 'accord-executor')));
      // the plain executor never carries the build skill (a static file cannot depend on the ticket)
      expect(plain.skills).toBeUndefined();
    });
  }

  it('risk:regression agents.executor additions follow the ui.build skill and the executor keeps its own (11-ac-8, D-07)', () => {
    const c = config({ ui: { build: 'impeccable:impeccable' }, agents: { executor: { skills: ['house-style', 'impeccable:impeccable'], mcp: ['playwright'] } } });
    const fm = frontmatter(fileOf(c, UI_EXECUTOR));
    // the ui.build skill is first and is not listed twice
    expect(fm.skills).toEqual(['impeccable:impeccable', 'house-style']);
    expect(fm.mcpServers).toEqual(['playwright']);
    expect(String(fm.tools).endsWith(', mcp__playwright__*')).toBe(true);
    // accord-executor keeps only its own additions, no ui.build skill
    expect(frontmatter(fileOf(c, 'accord-executor')).skills).toEqual(['house-style', 'impeccable:impeccable']);
    const without = config({ ui: { build: 'impeccable' }, agents: { executor: { skills: ['house-style'] } } });
    expect(frontmatter(fileOf(without, 'accord-executor')).skills).toEqual(['house-style']);
    expect(frontmatter(fileOf(without, UI_EXECUTOR)).skills).toEqual(['impeccable', 'house-style']);
  });

  it('risk:regression with no ui key the list of rendered paths and every text is what it is without the feature (11-ac-8, D-07)', () => {
    const plain = agentTargets(config());
    expect(plain.map((f) => f.path)).not.toContain('.claude/agents/accord-executor-ui.md');
    expect(plain.map((f) => f.path)).not.toContain('.claude/agents/accord-reviewer-ui.md');
    expect(agentTargets(config({ ui: {} }))).toEqual(plain);
    // ui.direction and ui.screenshots render no agent file
    expect(agentTargets(config({ ui: { direction: 'ui-ux-pro-max', screenshots: 'npx playwright test' } }))).toEqual(plain);
  });

  it('risk:regression ui.build adds exactly one file and changes no other (11-ac-8, D-07)', () => {
    const plain = agentTargets(config());
    const withUi = agentTargets(config({ ui: { build: 'impeccable' } }));
    expect(withUi.map((f) => f.path)).toEqual([...plain.map((f) => f.path), '.claude/agents/accord-executor-ui.md'].sort());
    for (const f of plain) expect(withUi.find((g) => g.path === f.path)?.text, f.path).toBe(f.text);
  });

  it('risk:regression a models.executor route reaches accord-executor-ui too (11-ac-8, D-07)', () => {
    const fm = frontmatter(fileOf(config({ ui: { build: 'impeccable' }, models: { executor: { model: 'opus', effort: 'max' } } }), UI_EXECUTOR));
    expect(fm.model).toBe('opus');
    expect(fm.effort).toBe('max');
  });

  it('risk:regression no agent file is rendered for a config without the claude runtime (11-ac-8, D-07)', () => {
    expect(agentTargets(config({ runtimes: ['codex'], ui: { build: 'impeccable', review: 'impeccable' } }))).toEqual([]);
  });
});

describe('ui.review renders accord-reviewer-ui from the reviewer definition (11-ac-8, D-07)', () => {
  for (const form of FORMS) {
    it(`risk:regression ui.review ${form} renders accord-reviewer-ui with that skill first and the reviewer's fields (11-ac-8, D-07)`, () => {
      const c = config({ ui: { review: form }, agents: { reviewer: { skills: ['house-style'], mcp: ['docs'] } } });
      const ui = fileOf(c, UI_REVIEWER);
      expect(ui, 'the variant is rendered').toBeDefined();
      const fm = frontmatter(ui);
      const plain = frontmatter(fileOf(c, 'accord-reviewer'));
      expect(fm.name).toBe('accord-reviewer-ui');
      expect(fm.skills).toEqual([form, 'house-style']);
      expect(fm.mcpServers).toEqual(['docs']);
      expect(fm.tools).toBe(plain.tools);
      expect(fm.model).toBe(plain.model);
      expect(fm.effort).toBe(plain.effort);
      // the plain reviewer keeps only its own additions
      expect(plain.skills).toEqual(['house-style']);
    });
  }

  it('risk:security ui.review never reaches the judge, the foreign reviewer, the final reviewer or the plain reviewer (11-ac-8, D-07, T-11-25)', () => {
    const base = config({ agents: { reviewer: { skills: ['house-style'] } } });
    const withUi = config({ agents: { reviewer: { skills: ['house-style'] } }, ui: { review: 'impeccable', build: 'impeccable' } });
    for (const name of ['accord-judge', 'accord-foreign-reviewer', 'accord-reviewer', 'accord-final-reviewer', 'accord-critic', 'accord-planner', 'accord-scout', 'accord-verifier', 'accord-debugger']) {
      const a = fileOf(base, name);
      expect(a, name).toBeDefined();
      expect(fileOf(withUi, name), name).toBe(a);
    }
    for (const name of ['accord-judge', 'accord-foreign-reviewer']) expect(frontmatter(fileOf(withUi, name)).skills, name).toBeUndefined();
    // ui.review adds one file and ui.build one more
    expect(agentTargets(withUi).length).toBe(agentTargets(base).length + 2);
  });

  it('risk:regression ui.review alone renders no executor variant and ui.build alone no reviewer variant (11-ac-8, D-07)', () => {
    const paths = (c: AccordConfig): string[] => agentTargets(c).map((f) => f.path);
    expect(paths(config({ ui: { review: 'impeccable' } }))).not.toContain('.claude/agents/accord-executor-ui.md');
    expect(paths(config({ ui: { review: 'impeccable' } }))).toContain('.claude/agents/accord-reviewer-ui.md');
    expect(paths(config({ ui: { build: 'impeccable' } }))).not.toContain('.claude/agents/accord-reviewer-ui.md');
  });
});
