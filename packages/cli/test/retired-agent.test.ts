// ST-LN-80: `accord skills sync` removes the architect agent accord once rendered, only while its marker shows no edit.
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { contentHash } from '@accord-dev/accord-core';
import { afterEach, expect, it } from 'vitest';
import { cleanup, makeRepo, run } from './helpers/repo.js';

const AGENT = '.claude/agents/accord-architect.md';
const at = (repo: string, path: string): string => join(repo, ...path.split('/'));

/** An intact old render of the architect agent: its marker hash is the hash of the text around it. */
function rendered(): string {
  const head = '---\nname: "accord-architect"\ntools: "Read, Grep, Glob"\nmodel: "opus"\neffort: "high"\n---\n';
  const body = '\nYou propose how a ticket could be built, lightest first.\n';
  return head + '<!-- generated by accord skills sync - do not edit - ' + contentHash(head + body) + ' -->\n' + body;
}

const repos: string[] = [];
afterEach(() => {
  while (repos.length > 0) cleanup(repos.pop() as string);
});

function sandbox(runtimes: string): string {
  const repo = makeRepo('valid-build');
  repos.push(repo);
  const file = join(repo, 'accord', 'config.yml');
  writeFileSync(file, readFileSync(file, 'utf8').replace(/^runtimes: .*$/m, 'runtimes: ' + runtimes));
  return repo;
}

function put(repo: string, text: string): void {
  mkdirSync(at(repo, '.claude/agents'), { recursive: true });
  writeFileSync(at(repo, AGENT), text);
}

function files(dir: string): string[] {
  return existsSync(dir) ? readdirSync(dir, { recursive: true, withFileTypes: true }).filter((e) => e.isFile()).map((e) => join(e.parentPath, e.name)) : [];
}

it('ac-1 sync removes the rendered architect agent and lint accepts models architect with a warning', async () => {
  const repo = sandbox('[claude, codex]');
  const cfg = join(repo, 'accord', 'config.yml');
  writeFileSync(cfg, readFileSync(cfg, 'utf8') + '\nmodels:\n  architect:\n    model: opus\n    effort: high\n');
  put(repo, rendered());

  const first = await run(['skills', 'sync'], repo);
  expect(first.code, first.err).toBe(0);
  expect(first.out.split('\n')).toContain('removed ' + AGENT);
  expect(existsSync(at(repo, AGENT))).toBe(false);
  const agents = readdirSync(at(repo, '.claude/agents'));
  expect(agents).toContain('accord-planner.md');
  expect(agents).not.toContain('accord-architect.md');
  for (const dir of ['.claude/skills', '.agents/skills', '.claude/agents']) {
    for (const f of files(at(repo, dir))) expect(readFileSync(f, 'utf8'), f).not.toContain('accord-architect');
  }

  const second = await run(['skills', 'sync'], repo);
  expect(second.out).not.toContain('removed');

  const lint = await run(['lint', '--json'], repo);
  expect(lint.code, lint.out + lint.err).toBe(0);
  const retired = (JSON.parse(lint.out) as { findings: { rule: string; level: string; file: string; pointer: string; reason: string }[] }).findings.filter(
    (f) => f.rule === 'lint.model-retired',
  );
  expect(retired).toHaveLength(1);
  expect(retired[0]).toMatchObject({ level: 'warning', file: 'accord/config.yml', pointer: '/models/architect' });
  expect(retired[0]?.reason).toContain('models.planner');
}, 120_000);

it('risk:data-loss sync keeps an edited architect agent and reports it as an orphan', async () => {
  const repo = sandbox('[claude, codex]');
  const edited = rendered() + 'a hand edit\n';
  put(repo, edited);

  const r = await run(['skills', 'sync'], repo);
  expect(r.code, r.err).toBe(0);
  expect(readFileSync(at(repo, AGENT), 'utf8')).toBe(edited);
  expect(r.out).not.toContain('removed');
  expect(r.err).toContain('orphan ' + AGENT);
}, 120_000);

it('risk:security sync removes no retired agent through a linked agents folder', async () => {
  const repo = sandbox('[codex]');
  const outside = mkdtempSync(join(tmpdir(), 'accord-outside-'));
  repos.push(outside);
  writeFileSync(join(outside, 'accord-architect.md'), rendered());
  mkdirSync(at(repo, '.claude'), { recursive: true });
  symlinkSync(outside, at(repo, '.claude/agents'), 'junction');

  const r = await run(['skills', 'sync'], repo);
  expect(r.code, r.err).toBe(0);
  expect(readFileSync(join(outside, 'accord-architect.md'), 'utf8')).toBe(rendered());
  expect(r.out).not.toContain('accord-architect');
  expect(r.err).not.toContain('accord-architect');
}, 120_000);
